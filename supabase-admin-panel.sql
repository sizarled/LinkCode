-- LinkCode Admin Panel backend
-- Run after the registration, login, profiles, dashboard, redirect and report SQL files.
-- Default credentials: Admin = admin/admin, Moderator = moderator/moderator.
-- Change these immediately from Panel > Admin settings.

create extension if not exists pgcrypto with schema extensions;

alter table public."Links" add column if not exists admin_publication_blocked boolean not null default false;
alter table public."Links" add column if not exists admin_publication_blocked_at timestamp with time zone null;
alter table public."Links" add column if not exists admin_publication_blocked_by text null;
alter table public."Links" add column if not exists admin_previous_visibility text null;
alter table public."Links" add column if not exists admin_previous_find_status text null;

-- Older blocked rows were created only from public links, so give them a safe
-- restoration target when no previous-state snapshot exists.
update public."Links"
set admin_previous_visibility = coalesce(admin_previous_visibility, 'Public'),
    admin_previous_find_status = coalesce(admin_previous_find_status, 'Active')
where admin_publication_blocked = true;

alter table public."Reports" add column if not exists destination_link text null;

update public."Reports" r
set destination_link = l.destination_link
from public."Links" l
where trim(l.code) = trim(r.code)
  and r.owner_id = l.owner_id
  and r.destination_link is null;

create table if not exists public."AdminMembers" (
  owner_id text primary key references public."Members" (owner_id) on delete cascade,
  admin_role text not null,
  admin_status text not null default 'Active',
  added_by text null,
  added_at timestamp with time zone not null default now(),
  constraint admin_members_role_valid check (admin_role in ('Admin','Moderator')),
  constraint admin_members_status_valid check (admin_status in ('Active','Disabled'))
);

create table if not exists public."AdminCredentials" (
  admin_role text primary key,
  username text not null unique,
  password_hash text not null,
  must_change_password boolean not null default true,
  updated_at timestamp with time zone not null default now(),
  constraint admin_credentials_role_valid check (admin_role in ('Admin','Moderator')),
  constraint admin_credentials_username_valid check (username ~ '^[A-Za-z0-9_]{3,30}$')
);

create table if not exists public."AdminSessions" (
  session_id uuid primary key default gen_random_uuid(),
  owner_id text not null references public."Members" (owner_id) on delete cascade,
  admin_role text not null,
  token_hash text not null unique,
  created_at timestamp with time zone not null default now(),
  expires_at timestamp with time zone not null,
  last_seen_at timestamp with time zone not null default now(),
  constraint admin_sessions_role_valid check (admin_role in ('Admin','Moderator'))
);

create table if not exists public."AdminActions" (
  id bigint generated by default as identity primary key,
  admin_owner_id text not null,
  admin_role text not null,
  action_type text not null,
  target_type text null,
  target_id text null,
  action_details jsonb null,
  action_date timestamp with time zone not null default now()
);

