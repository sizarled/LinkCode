create or replace function public.panel_update_report_status(
  p_admin_token text,
  p_report_id bigint,
  p_status text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_admin text;
  v_role text;
  v_owner text;
  v_code text;
  v_subject text;
  v_destination text;
  v_affected bigint;
begin
  select c.owner_id, c.admin_role into v_admin, v_role
  from public.panel_session_context(p_admin_token) c;
  if v_admin is null then return jsonb_build_object('success', false, 'reason', 'UNAUTHORIZED'); end if;
  if p_status not in ('Valid','Expired') then return jsonb_build_object('success', false, 'reason', 'INVALID_STATUS'); end if;

  select r.owner_id, trim(r.code), r.report_subject, coalesce(r.destination_link, l.destination_link)
  into v_owner, v_code, v_subject, v_destination
  from public."Reports" r
  left join public."Links" l on trim(l.code) = trim(r.code) and l.owner_id = r.owner_id
  where r.id = p_report_id
  limit 1;
  if v_owner is null then return jsonb_build_object('success', false, 'reason', 'REPORT_NOT_FOUND'); end if;
  if v_role='Moderator' and exists(select 1 from public."AdminMembers" where owner_id=v_owner) then
    return jsonb_build_object('success',false,'reason','ADMIN_TARGET_PROTECTED');
  end if;

  perform pg_advisory_xact_lock(hashtext('report-decision:' || v_owner || ':' || v_code || ':' || v_subject || ':' || coalesce(v_destination,'')));

  update public."Reports" r
  set report_status = p_status,
      destination_link = coalesce(r.destination_link, v_destination)
  where r.owner_id = v_owner
    and trim(r.code) = v_code
    and r.report_subject = v_subject
    and coalesce(
      r.destination_link,
      (select l.destination_link from public."Links" l where trim(l.code) = v_code and l.owner_id = v_owner limit 1),
      ''
    ) = coalesce(v_destination, '');
  get diagnostics v_affected = row_count;

  if to_regprocedure('public.evaluate_link_report_block(text,text)') is not null then
    execute 'select public.evaluate_link_report_block($1,$2)' using v_owner, v_code;
  end if;

  insert into public."AdminActions" (admin_owner_id, admin_role, action_type, target_type, target_id, action_details)
  values (v_admin, v_role, 'UPDATE_REPORT_GROUP', 'Report', p_report_id::text,
    jsonb_build_object('status', p_status, 'affected_reports', v_affected, 'owner_id', v_owner, 'code', v_code, 'subject', v_subject, 'destination', v_destination));

  return jsonb_build_object('success', true, 'affected_reports', v_affected, 'status', p_status);
end;
$$;
revoke all on function public.panel_update_report_status(text,bigint,text) from public;
grant execute on function public.panel_update_report_status(text,bigint,text) to anon, authenticated;

