create or replace function public.panel_update_member_status(
  p_admin_token text, p_owner_id text, p_status text
) returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare v_admin text; v_role text; v_target_role text;
begin
  select c.owner_id,c.admin_role into v_admin,v_role from public.panel_session_context(p_admin_token)c;
  if v_admin is null then return jsonb_build_object('success',false,'reason','UNAUTHORIZED'); end if;
  if p_status not in ('Active','Expired','Banned') then return jsonb_build_object('success',false,'reason','INVALID_STATUS'); end if;
  if p_owner_id=v_admin then return jsonb_build_object('success',false,'reason','CANNOT_MODIFY_SELF'); end if;
  select admin_role into v_target_role from public."AdminMembers" where owner_id=p_owner_id;
  if v_role='Moderator' and v_target_role is not null then return jsonb_build_object('success',false,'reason','ADMIN_TARGET_PROTECTED'); end if;
  update public."Members" set account_status=p_status where owner_id=p_owner_id;
  if not found then return jsonb_build_object('success',false,'reason','MEMBER_NOT_FOUND'); end if;
  insert into public."AdminActions"(admin_owner_id,admin_role,action_type,target_type,target_id,action_details)
  values(v_admin,v_role,'UPDATE_MEMBER_STATUS','Member',p_owner_id,jsonb_build_object('status',p_status));
  return jsonb_build_object('success',true);
end; $$;
revoke all on function public.panel_update_member_status(text,text,text) from public;
grant execute on function public.panel_update_member_status(text,text,text) to anon, authenticated;

create or replace function public.panel_update_link(
  p_admin_token text, p_link_id bigint, p_status text, p_waiting_time integer, p_level text
) returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare v_admin text; v_role text; v_target_owner text; v_code text;
begin
  select c.owner_id,c.admin_role into v_admin,v_role from public.panel_session_context(p_admin_token)c;
  if v_admin is null then return jsonb_build_object('success',false,'reason','UNAUTHORIZED'); end if;
  select owner_id,trim(code) into v_target_owner,v_code from public."Links" where id=p_link_id;
  if v_target_owner is null then return jsonb_build_object('success',false,'reason','LINK_NOT_FOUND'); end if;
  if v_role='Moderator' and exists(select 1 from public."AdminMembers" where owner_id=v_target_owner) then
    return jsonb_build_object('success',false,'reason','ADMIN_TARGET_PROTECTED');
  end if;
  if p_status not in ('Active','Inactive','Blocked') then return jsonb_build_object('success',false,'reason','INVALID_STATUS'); end if;
  if p_waiting_time not between 30 and 90 then return jsonb_build_object('success',false,'reason','INVALID_WAITING_TIME'); end if;
  if p_level not in ('LV0','LV1','LV2','LV3','LV4','LV5') then return jsonb_build_object('success',false,'reason','INVALID_LEVEL'); end if;
  update public."Links" set code_status=p_status,waiting_time=p_waiting_time,link_level=p_level where id=p_link_id;
  if not found then return jsonb_build_object('success',false,'reason','LINK_NOT_FOUND'); end if;
  update public."Find" f set waiting_time=p_waiting_time,link_level=p_level,
    link_status=case when p_status='Active' then f.link_status when p_status='Blocked' then 'Blocked' else 'Disabled' end
  where trim(f.code)=(select trim(code) from public."Links" where id=p_link_id);
  if to_regprocedure('public.evaluate_link_report_block(text,text)') is not null then
    execute 'select public.evaluate_link_report_block($1,$2)' using v_target_owner,v_code;
  end if;
  insert into public."AdminActions"(admin_owner_id,admin_role,action_type,target_type,target_id,action_details)
  values(v_admin,v_role,'UPDATE_LINK','Link',p_link_id::text,jsonb_build_object('status',p_status,'level',p_level,'waiting_time',p_waiting_time));
  return jsonb_build_object('success',true);
end; $$;
