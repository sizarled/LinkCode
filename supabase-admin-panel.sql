create or replace function public.panel_session_context(p_admin_token text)
returns table (owner_id text, admin_role text)
language sql
stable
security definer
set search_path = public, extensions
as $$
  select s.owner_id, s.admin_role
  from public."AdminSessions" s
  join public."AdminMembers" a on a.owner_id = s.owner_id and a.admin_status = 'Active' and a.admin_role = s.admin_role
  join public."Members" m on m.owner_id = s.owner_id and m.account_status = 'Active'
  where p_admin_token ~ '^[a-f0-9]{64}$'
    and s.token_hash = encode(digest(p_admin_token, 'sha256'), 'hex')
    and s.expires_at > now()
  limit 1;
$$;
revoke all on function public.panel_session_context(text) from public;

create or replace function public.panel_login(
  p_member_session_token text,
  p_username text,
  p_password text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_owner text;
  v_credential public."AdminCredentials"%rowtype;
  v_admin public."AdminMembers"%rowtype;
  v_token text;
  v_expires timestamp with time zone;
begin
  if p_member_session_token is null or p_member_session_token !~ '^[a-f0-9]{64}$' then
    return jsonb_build_object('success', false, 'reason', 'MEMBER_SESSION_REQUIRED');
  end if;

  select s.owner_id into v_owner
  from public."MemberSessions" s
  join public."Members" m on m.owner_id = s.owner_id
  where s.token_hash = encode(digest(p_member_session_token, 'sha256'), 'hex')
    and s.expires_at > now()
    and m.account_status = 'Active'
  limit 1;
  if v_owner is null then return jsonb_build_object('success', false, 'reason', 'MEMBER_SESSION_REQUIRED'); end if;

  select * into v_credential
  from public."AdminCredentials"
  where lower(username) = lower(trim(coalesce(p_username, '')))
  limit 1;
  if not found or v_credential.password_hash <> crypt(coalesce(p_password, ''), v_credential.password_hash) then
    return jsonb_build_object('success', false, 'reason', 'INVALID_ADMIN_CREDENTIALS');
  end if;

  -- The first successful admin/admin login bootstraps the first administrator.
  if v_credential.admin_role = 'Admin'
     and not exists (select 1 from public."AdminMembers" where admin_status = 'Active')
     and v_owner = (select m.owner_id from public."Members" m order by m.joining_date asc, m.owner_id asc limit 1) then
    insert into public."AdminMembers" (owner_id, admin_role, admin_status, added_by)
    values (v_owner, 'Admin', 'Active', v_owner)
    on conflict (owner_id) do update set admin_role = 'Admin', admin_status = 'Active';
  end if;

  select * into v_admin from public."AdminMembers" where owner_id = v_owner;
  if not found or v_admin.admin_status <> 'Active' then
    return jsonb_build_object('success', false, 'reason', 'ADMIN_ACCESS_DENIED');
  end if;
  if v_admin.admin_role <> v_credential.admin_role then
    return jsonb_build_object('success', false, 'reason', 'ROLE_CREDENTIAL_MISMATCH');
  end if;

  v_token := encode(gen_random_bytes(32), 'hex');
  v_expires := now() + interval '2 hours';
  insert into public."AdminSessions" (owner_id, admin_role, token_hash, expires_at)
  values (v_owner, v_admin.admin_role, encode(digest(v_token, 'sha256'), 'hex'), v_expires);

  insert into public."AdminActions" (admin_owner_id, admin_role, action_type, target_type, target_id)
  values (v_owner, v_admin.admin_role, 'PANEL_LOGIN', 'Member', v_owner);

  return jsonb_build_object(
    'success', true,
    'admin_token', v_token,
    'admin_role', v_admin.admin_role,
    'expires_at', v_expires,
    'must_change_password', v_credential.must_change_password
  );
end;
$$;
revoke all on function public.panel_login(text, text, text) from public;
grant execute on function public.panel_login(text, text, text) to anon, authenticated;

