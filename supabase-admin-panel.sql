create or replace function public.panel_record_payment(
  p_admin_token text,p_owner_id text,p_amount numeric,p_reference text
) returns jsonb language plpgsql security definer set search_path=public,extensions as $$
declare v_admin text;v_role text;v_available numeric;v_method text;
begin
  select c.owner_id,c.admin_role into v_admin,v_role from public.panel_session_context(p_admin_token)c;
  if v_admin is null then return jsonb_build_object('success',false,'reason','UNAUTHORIZED'); end if;
  select m.account_earnings-m.account_payments,pa.payment_method into v_available,v_method
  from public."Members"m left join public."PaymentAccounts"pa on pa.owner_id=m.owner_id where m.owner_id=p_owner_id for update of m;
