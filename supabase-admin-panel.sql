  insert into public."Payments"(owner_id,amount,payment_method,payment_status,payment_reference)
  values(p_owner_id,p_amount,v_method,'Paid',nullif(trim(p_reference),''));
  update public."Members"set account_payments=account_payments+p_amount where owner_id=p_owner_id;
  insert into public."AdminActions"(admin_owner_id,admin_role,action_type,target_type,target_id,action_details)
  values(v_admin,v_role,'RECORD_PAYMENT','Member',p_owner_id,jsonb_build_object('amount',p_amount,'method',v_method));
  return jsonb_build_object('success',true);
end; $$;
