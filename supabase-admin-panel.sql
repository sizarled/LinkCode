-- Seed the first registered member as the initial administrator. This makes the
-- Dashboard Panel button visible only to an authorized member from first setup.
insert into public."AdminMembers" (owner_id, admin_role, admin_status, added_by)
select m.owner_id, 'Admin', 'Active', m.owner_id
from public."Members" m
where not exists (select 1 from public."AdminMembers")
order by m.joining_date asc, m.owner_id asc
limit 1
on conflict (owner_id) do nothing;

create or replace function public.bootstrap_first_admin_member()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform pg_advisory_xact_lock(hashtext('linkcode-first-admin'));
  if not exists (select 1 from public."AdminMembers") then
    insert into public."AdminMembers" (owner_id, admin_role, admin_status, added_by)
    values (new.owner_id, 'Admin', 'Active', new.owner_id)
    on conflict (owner_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists members_bootstrap_first_admin_trigger on public."Members";
create trigger members_bootstrap_first_admin_trigger
after insert on public."Members"
for each row execute function public.bootstrap_first_admin_member();

