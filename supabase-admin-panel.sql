create or replace function public.panel_set_publication_block(
  p_admin_token text,
  p_link_id bigint,
  p_blocked boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_admin text;
  v_role text;
  v_code text;
  v_target_owner text;
  v_is_blocked boolean;
  v_previous_visibility text;
  v_previous_status text;
  v_current_visibility text;
  v_current_status text;
begin
  select c.owner_id,c.admin_role into v_admin,v_role from public.panel_session_context(p_admin_token)c;
  if v_admin is null then return jsonb_build_object('success',false,'reason','UNAUTHORIZED'); end if;

  select trim(l.code),l.owner_id,l.admin_publication_blocked,l.admin_previous_visibility,l.admin_previous_find_status,
         f.visibility,f.link_status
  into v_code,v_target_owner,v_is_blocked,v_previous_visibility,v_previous_status,v_current_visibility,v_current_status
  from public."Links" l left join public."Find" f on trim(f.code)=trim(l.code)
  where l.id=p_link_id
  limit 1;
  if v_code is null then return jsonb_build_object('success',false,'reason','LINK_NOT_FOUND'); end if;

  if v_role='Moderator' and exists(select 1 from public."AdminMembers" where owner_id=v_target_owner) then
    return jsonb_build_object('success',false,'reason','ADMIN_TARGET_PROTECTED');
  end if;

  if coalesce(p_blocked,false) then
    if not coalesce(v_is_blocked,false) then
      update public."Links"
      set admin_publication_blocked=true,
          admin_publication_blocked_at=now(),
          admin_publication_blocked_by=v_admin,
          admin_previous_visibility=coalesce(v_current_visibility,'Private'),
          admin_previous_find_status=coalesce(v_current_status,'Disabled')
      where id=p_link_id;
      update public."Find" set visibility='Private',link_status='Blocked' where trim(code)=v_code;
    end if;
  else
    if coalesce(v_is_blocked,false) then
      update public."Links"
      set admin_publication_blocked=false,
          admin_publication_blocked_at=null,
          admin_publication_blocked_by=null
      where id=p_link_id;
      update public."Find"
      set visibility=coalesce(v_previous_visibility,'Private'),
          link_status=coalesce(v_previous_status,'Disabled')
      where trim(code)=v_code;
    end if;
  end if;

  insert into public."AdminActions"(admin_owner_id,admin_role,action_type,target_type,target_id,action_details)
  values(v_admin,v_role,case when p_blocked then 'BLOCK_PUBLICATION' else 'RESTORE_PUBLICATION' end,'Link',p_link_id::text,
    jsonb_build_object('code',v_code,'blocked',coalesce(p_blocked,false),'target_owner',v_target_owner));

  return jsonb_build_object('success',true,'blocked',coalesce(p_blocked,false),
    'visibility',case when p_blocked then 'Private' else coalesce(v_previous_visibility,'Private') end);
end;
$$;
revoke all on function public.panel_set_publication_block(text,bigint,boolean) from public;
grant execute on function public.panel_set_publication_block(text,bigint,boolean) to anon, authenticated;

