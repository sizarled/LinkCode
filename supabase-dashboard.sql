-- Resolve and validate a private browser session token ----------------------
create or replace function public.dashboard_session_owner(p_session_token text)
returns text
language sql
stable
security definer
set search_path = public, extensions
as $$
  select s.owner_id
  from public."MemberSessions" s
  join public."Members" m on m.owner_id = s.owner_id
  where p_session_token ~ '^[a-f0-9]{64}$'
    and s.token_hash = encode(digest(p_session_token, 'sha256'), 'hex')
    and s.expires_at > now()
    and m.account_status = 'Active'
  limit 1;
$$;

revoke all on function public.dashboard_session_owner(text) from public;

create or replace function public.account_level_for_visits(p_total_valid_visits bigint)
returns text
language sql
immutable
as $$
  select case
    when coalesce(p_total_valid_visits,0) >= 100000 then 'LV5'
    when coalesce(p_total_valid_visits,0) >= 10000 then 'LV4'
    when coalesce(p_total_valid_visits,0) >= 1000 then 'LV3'
    when coalesce(p_total_valid_visits,0) >= 100 then 'LV2'
    when coalesce(p_total_valid_visits,0) >= 10 then 'LV1'
    else 'LV0'
  end;
$$;
revoke all on function public.account_level_for_visits(bigint) from public;
grant execute on function public.account_level_for_visits(bigint) to anon,authenticated;

-- Dashboard bootstrap -------------------------------------------------------
create or replace function public.dashboard_get_data(p_session_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_owner text := public.dashboard_session_owner(p_session_token);
  v_result jsonb;
  v_admin_access jsonb := jsonb_build_object('allowed', false, 'admin_role', null);
begin
  if v_owner is null then
    return jsonb_build_object('success', false, 'reason', 'UNAUTHORIZED');
  end if;

  insert into public."Profiles" (
    id, username, full_name, email, number_of_followers, profile_status, joined_date
  )
  select m.owner_id, 'member_' || lower(m.owner_id), m.full_name, lower(m.email), 0,
         case m.account_status when 'Active' then 'Active' when 'Banned' then 'Banned' else 'Inactive' end,
         m.joining_date
  from public."Members" m where m.owner_id = v_owner
  on conflict (id) do nothing;

  -- AdminMembers is installed by the optional Panel migration. Dynamic SQL
  -- keeps the member dashboard usable even before that migration is installed.
  if to_regclass('public."AdminMembers"') is not null then
    execute '
      select jsonb_build_object(''allowed'', true, ''admin_role'', a.admin_role)
      from public."AdminMembers" a
      where a.owner_id = $1 and a.admin_status = ''Active''
      limit 1'
    into v_admin_access
    using v_owner;
    v_admin_access := coalesce(v_admin_access, jsonb_build_object('allowed', false, 'admin_role', null));
  end if;

  select jsonb_build_object(
    'success', true,
    'admin_access', v_admin_access,
    'member', (
      select jsonb_build_object(
        'owner_id', m.owner_id,
        'full_name', m.full_name,
        'email', m.email,
        'account_status', m.account_status,
        'joining_date', m.joining_date,
        'account_earnings', m.account_earnings,
        'account_payments', m.account_payments,
        'total_valid_visits', (select count(*) from public."Visits" v where v.owner_id = m.owner_id),
        'account_level', public.account_level_for_visits((select count(*) from public."Visits" v where v.owner_id = m.owner_id))
      ) from public."Members" m where m.owner_id = v_owner
    ),
    'profile', (
      select jsonb_build_object(
        'username', p.username,
        'avatar_url', p.avatar_url,
        'bio', p.bio,
        'followers', (select count(*) from public."Follows" f where f.following_id = v_owner),
        'following', (select count(*) from public."Follows" f where f.follower_id = v_owner)
      ) from public."Profiles" p where p.id = v_owner
    ),
    'followers', coalesce((
      select jsonb_agg(jsonb_build_object('owner_id', p.id, 'username', p.username, 'avatar_url', p.avatar_url) order by f.followed_at desc)
      from public."Follows" f join public."Profiles" p on p.id = f.follower_id
      where f.following_id = v_owner
    ), '[]'::jsonb),
    'following', coalesce((
      select jsonb_agg(jsonb_build_object('owner_id', p.id, 'username', p.username, 'avatar_url', p.avatar_url) order by f.followed_at desc)
      from public."Follows" f join public."Profiles" p on p.id = f.following_id
      where f.follower_id = v_owner
    ), '[]'::jsonb),
    'following_posts', coalesce((
      select jsonb_agg(jsonb_build_object(
        'owner_id', pub.owner_id,
        'publisher_username', coalesce(lp.username, pub.owner_id),
        'publisher_avatar', lp.avatar_url,
        'code', trim(pub.code),
        'title', pub.link_title,
        'description', trim(pub.link_description),
        'tags', pub.link_tags,
        'waiting_time', pub.waiting_time,
        'link_level', pub.link_level,
        'publisher_bonus', pub.publisher_bonus,
        'publisher_bonus_percentage', pub.publisher_bonus_percentage,
        'creation_date', pub.link_creation_date,
        'publication_date', pub.link_publication_date,
        'thumbnail_url', pub.thumbnail_url,
        'impressions', pub.images,
        'clicks', pub.clicks,
        'visits', coalesce(l.number_of_visits, pub.visits)
      ) order by pub.link_publication_date desc nulls last)
      from public."Follows" follow
      join public."Find" pub on pub.owner_id = follow.following_id
      join public."Links" l on trim(l.code) = trim(pub.code)
      left join public."Profiles" lp on lp.id = pub.owner_id
      where follow.follower_id = v_owner
        and not exists(select 1 from public."MemberBlocks"b where b.block_scope='Full' and ((b.blocker_id=pub.owner_id and b.blocked_id=v_owner)or(b.blocker_id=v_owner and b.blocked_id=pub.owner_id)))
        and pub.visibility = 'Public'
        and pub.link_status = 'Active'
        and l.code_status = 'Active'
        and (l.link_expiration_date is null or l.link_expiration_date > now())
    ), '[]'::jsonb),
    'links', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', l.id, 'code', trim(l.code), 'code_status', l.code_status,
        'waiting_time', l.waiting_time, 'destination_link', l.destination_link,
        'link_level', l.link_level, 'publisher_bonus_status', l.publisher_bonus_status,
        'publisher_bonus_percentage', l.publisher_bonus_percentage,
        'number_of_visits', l.number_of_visits, 'number_of_reports', l.number_of_reports,
        'admin_publication_blocked', coalesce((to_jsonb(l)->>'admin_publication_blocked')::boolean, false),
        'report_auto_blocked', coalesce((to_jsonb(l)->>'report_auto_blocked')::boolean, false),
        'report_auto_block_subject', to_jsonb(l)->>'report_auto_block_subject',
        'report_auto_block_count', coalesce((to_jsonb(l)->>'report_auto_block_count')::bigint, 0),
        'link_creation_date', l.link_creation_date, 'link_expiration_date', l.link_expiration_date,
        'link_last_visit_date', l.link_last_visit_date,
        'earnings', coalesce((select sum(v.visit_earnings) from public."Visits" v where v.owner_id = v_owner and trim(v.code) = trim(l.code)), 0),
        'visibility', coalesce(f.visibility, 'Private'),
        'published', (f.id is not null and f.visibility = 'Public'),
        'title', f.link_title, 'description', trim(f.link_description),
        'tags', f.link_tags, 'thumbnail_url', f.thumbnail_url,
        'impressions', coalesce(f.images, 0), 'clicks', coalesce(f.clicks, 0)
      ) order by l.link_creation_date desc)
      from public."Links" l left join public."Find" f on trim(f.code) = trim(l.code)
      where l.owner_id = v_owner
    ), '[]'::jsonb),
    'reports', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', r.id, 'code', trim(r.code), 'link_level', r.link_level,
        'report_subject', r.report_subject, 'report_status', r.report_status,
        'report_date', r.report_date
      ) order by r.report_date desc)
      from public."Reports" r where r.owner_id = v_owner
    ), '[]'::jsonb),
    'gifts_given', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', g.id, 'code', trim(g.code), 'beneficiary_owner_id', g.beneficiary_owner_id,
        'beneficiary_username', p.username, 'gift_percentage', g.gift_percentage,
