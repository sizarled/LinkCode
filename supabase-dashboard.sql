-- Create or edit a private link ---------------------------------------------
create or replace function public.dashboard_save_link(
  p_session_token text,
  p_link_id bigint,
  p_code text,
  p_code_status text,
  p_waiting_time integer,
  p_destination_link text,
  p_link_level text,
  p_publisher_bonus_status text,
  p_publisher_bonus_percentage numeric,
  p_expiration_date timestamp with time zone
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_owner text := public.dashboard_session_owner(p_session_token);
  v_existing public."Links"%rowtype;
  v_visits bigint := 0;
  v_required bigint := 0;
  v_id bigint;
  v_valid_expiration boolean := false;
  v_expiration_days numeric;
  v_destination text := trim(coalesce(p_destination_link, ''));
begin
  if v_owner is null then return jsonb_build_object('success', false, 'reason', 'UNAUTHORIZED'); end if;
  if p_code !~ '^[0-9]{6}$' then return jsonb_build_object('success', false, 'reason', 'INVALID_CODE'); end if;
  if p_code_status not in ('Active','Inactive') then return jsonb_build_object('success', false, 'reason', 'INVALID_STATUS'); end if;
  if p_waiting_time not between 30 and 90 then return jsonb_build_object('success', false, 'reason', 'INVALID_WAITING_TIME'); end if;
  if v_destination !~* '^https?://[^[:space:]]+$' then return jsonb_build_object('success', false, 'reason', 'INVALID_DESTINATION'); end if;
  if p_link_level not in ('LV0','LV1','LV2','LV3','LV4','LV5') then return jsonb_build_object('success', false, 'reason', 'INVALID_LEVEL'); end if;
  if p_publisher_bonus_status not in ('Enabled','Disabled') then return jsonb_build_object('success', false, 'reason', 'INVALID_BONUS'); end if;
  if p_publisher_bonus_percentage < 0 or p_publisher_bonus_percentage > 25 then return jsonb_build_object('success', false, 'reason', 'INVALID_BONUS_PERCENTAGE'); end if;
  if p_publisher_bonus_status = 'Disabled' and p_publisher_bonus_percentage <> 0 then return jsonb_build_object('success', false, 'reason', 'BONUS_DISABLED_PERCENTAGE'); end if;
  if p_publisher_bonus_status = 'Enabled' and p_link_level not in ('LV3','LV4','LV5') then return jsonb_build_object('success', false, 'reason', 'BONUS_LEVEL_REQUIRED'); end if;
  if p_expiration_date is null or p_expiration_date <= now() then return jsonb_build_object('success', false, 'reason', 'INVALID_EXPIRATION'); end if;

  perform pg_advisory_xact_lock(hashtext('link-code:' || p_code));
  perform pg_advisory_xact_lock(hashtext('link-destination:' || lower(v_destination)));

  -- Link levels are unlocked by the member's all-time total of valid Visits,
  -- not by the visit count of the individual link being edited.
  select count(*)::bigint into v_visits
  from public."Visits" v
  where v.owner_id = v_owner;

  if p_link_id is not null then
    select * into v_existing from public."Links" where id = p_link_id and owner_id = v_owner for update;
    if not found then return jsonb_build_object('success', false, 'reason', 'LINK_NOT_FOUND'); end if;
  end if;

  -- Only 1, 3, 6, or 12-month periods are accepted. An unchanged future
  -- expiration remains valid while editing; expired links receive a new period.
  if p_link_id is not null and v_existing.link_expiration_date = p_expiration_date and p_expiration_date > now() then
    v_valid_expiration := true;
  else
    v_expiration_days := extract(epoch from (p_expiration_date - now())) / 86400;
    v_valid_expiration := v_expiration_days between 27 and 32
      or v_expiration_days between 88 and 93
      or v_expiration_days between 180 and 185
      or v_expiration_days between 364 and 367;
  end if;
  if not v_valid_expiration then
    return jsonb_build_object('success', false, 'reason', 'INVALID_EXPIRATION_PERIOD');
  end if;

  if exists (select 1 from public."DeletedLinks" where trim(code) = p_code) then
    return jsonb_build_object('success', false, 'reason', 'CODE_RETIRED');
  end if;
  if exists (select 1 from public."Links" where trim(code) = p_code and (p_link_id is null or id <> p_link_id)) then
    return jsonb_build_object('success', false, 'reason', 'CODE_EXISTS');
  end if;
  if exists (select 1 from public."Links" where lower(trim(destination_link)) = lower(v_destination) and (p_link_id is null or id <> p_link_id)) then
    return jsonb_build_object('success', false, 'reason', 'DESTINATION_EXISTS');
  end if;

  v_required := case p_link_level when 'LV1' then 10 when 'LV2' then 100 when 'LV3' then 1000 when 'LV4' then 10000 when 'LV5' then 100000 else 0 end;
  if v_visits < v_required then
    return jsonb_build_object(
      'success', false,
      'reason', 'ACCOUNT_LEVEL_LOCKED',
      'required_total_visits', v_required,
      'current_total_visits', v_visits,
      'requested_level', p_link_level
    );
  end if;

  if p_link_id is null then
    insert into public."Links" (owner_id, code, code_status, waiting_time, destination_link, link_level, publisher_bonus_status, publisher_bonus_percentage, link_expiration_date)
    values (v_owner, p_code, p_code_status, p_waiting_time, v_destination, p_link_level, p_publisher_bonus_status, p_publisher_bonus_percentage, p_expiration_date)
    returning id into v_id;
  else
    update public."Links" set code = p_code, code_status = p_code_status, waiting_time = p_waiting_time,
      destination_link = v_destination, link_level = p_link_level,
      publisher_bonus_status = p_publisher_bonus_status,
      publisher_bonus_percentage = p_publisher_bonus_percentage,
      link_expiration_date = p_expiration_date
    where id = p_link_id and owner_id = v_owner returning id into v_id;

    update public."Find" set code = p_code, waiting_time = p_waiting_time, link_level = p_link_level,
      publisher_bonus = p_publisher_bonus_status, publisher_bonus_percentage = p_publisher_bonus_percentage,
      link_expiration_date = p_expiration_date
    where owner_id = v_owner and trim(code) = trim(v_existing.code);
  end if;

  return jsonb_build_object('success', true, 'link_id', v_id, 'code', p_code);
end;
$$;

revoke all on function public.dashboard_save_link(text, bigint, text, text, integer, text, text, text, numeric, timestamp with time zone) from public;
grant execute on function public.dashboard_save_link(text, bigint, text, text, integer, text, text, text, numeric, timestamp with time zone) to anon, authenticated;

