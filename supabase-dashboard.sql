        and (l.link_expiration_date is null or l.link_expiration_date > now())
    ), '[]'::jsonb),
    'followers', coalesce((
      select jsonb_agg(jsonb_build_object(
        'owner_id', p.id, 'username', p.username, 'avatar_url', p.avatar_url
      ) order by f.followed_at desc)
      from public."Follows" f
      join public."Profiles" p on p.id = f.follower_id
      join public."Members" m on m.owner_id = p.id and m.account_status = 'Active'
      where f.following_id = v_profile.id
    ), '[]'::jsonb),
    'following', coalesce((
      select jsonb_agg(jsonb_build_object(
        'owner_id', p.id, 'username', p.username, 'avatar_url', p.avatar_url
      ) order by f.followed_at desc)
      from public."Follows" f
      join public."Profiles" p on p.id = f.following_id
      join public."Members" m on m.owner_id = p.id and m.account_status = 'Active'
      where f.follower_id = v_profile.id
    ), '[]'::jsonb)
  );
end;
$$;

