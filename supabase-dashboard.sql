create or replace function public.public_profile_follow(
  p_session_token text,
  p_username text,
  p_follow boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_viewer text := public.dashboard_session_owner(p_session_token);
  v_target text;
  v_count bigint;
begin
  if v_viewer is null then return jsonb_build_object('success', false, 'reason', 'UNAUTHORIZED'); end if;

  select p.id into v_target
  from public."Profiles" p
  join public."Members" m on m.owner_id = p.id
  where lower(p.username) = lower(trim(coalesce(p_username, '')))
    and p.profile_status = 'Active'
    and m.account_status = 'Active'
  limit 1;

  if v_target is null then return jsonb_build_object('success', false, 'reason', 'PROFILE_NOT_FOUND'); end if;
  if v_target = v_viewer then return jsonb_build_object('success', false, 'reason', 'CANNOT_FOLLOW_SELF'); end if;
  if exists(select 1 from public."MemberBlocks"where blocker_id=v_target and blocked_id=v_viewer and block_scope='Full') then
    return jsonb_build_object('success',false,'reason','PROFILE_BLOCKED');
  end if;

  if coalesce(p_follow, false) then
    insert into public."Follows" (follower_id, following_id)
    values (v_viewer, v_target)
    on conflict do nothing;
  else
    delete from public."Follows" where follower_id = v_viewer and following_id = v_target;
  end if;

  select count(*) into v_count from public."Follows" where following_id = v_target;
  return jsonb_build_object('success', true, 'following', coalesce(p_follow, false), 'followers', v_count);
end;
$$;

revoke all on function public.public_profile_follow(text, text, boolean) from public;
grant execute on function public.public_profile_follow(text, text, boolean) to anon, authenticated;

