create or replace function public.notify_new_message()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if new.recipient_type='Member' and new.recipient_id is not null then
    insert into public."Notifications"(recipient_id,notification_scope,notification_category,notification_title,notification_body,reference_type,reference_id)
    values(new.recipient_id,'Member','Messages',case when new.sender_type in('Admin','Moderator')then 'New administration message' else 'New member message'end,new.message_subject,'Message',new.id::text);
  elsif new.recipient_type='Support' and to_regclass('public."AdminMembers"') is not null then
    execute 'insert into public."Notifications"(recipient_id,notification_scope,notification_category,notification_title,notification_body,reference_type,reference_id)
