-- Permanent owner-controlled link deletion ---------------------------------
create or replace function public.dashboard_delete_link(
  p_session_token text,
  p_link_id bigint,
  p_confirmation_code text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_owner text := public.dashboard_session_owner(p_session_token);
  v_link public."Links"%rowtype;
begin
  if v_owner is null then return jsonb_build_object('success', false, 'reason', 'UNAUTHORIZED'); end if;

  select * into v_link
  from public."Links"
  where id = p_link_id and owner_id = v_owner
  for update;

  if not found then return jsonb_build_object('success', false, 'reason', 'LINK_NOT_FOUND'); end if;
  if p_confirmation_code is null or p_confirmation_code <> trim(v_link.code) then
    return jsonb_build_object('success', false, 'reason', 'CONFIRMATION_MISMATCH');
  end if;

  perform pg_advisory_xact_lock(hashtext('delete-link:' || trim(v_link.code)));

  insert into public."DeletedLinks" (
    owner_id, code, destination_link, link_level, code_status,
    number_of_visits, number_of_reports, link_creation_date
  ) values (
    v_link.owner_id, trim(v_link.code), v_link.destination_link,
    v_link.link_level, v_link.code_status, v_link.number_of_visits,
    v_link.number_of_reports, v_link.link_creation_date
  )
  on conflict (code) do nothing;

  -- Remove discovery metadata first, then the private link. Historical Visits,
  -- Reports, gifts, and financial records are intentionally retained.
  delete from public."Find" where owner_id = v_owner and trim(code) = trim(v_link.code);
  delete from public."Links" where id = v_link.id and owner_id = v_owner;

  return jsonb_build_object('success', true, 'deleted_code', trim(v_link.code));
end;
$$;

