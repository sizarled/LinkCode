create or replace function public.dashboard_set_link_visibility(p_session_token text, p_code text, p_public boolean)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare v_owner text := public.dashboard_session_owner(p_session_token);
begin
  if v_owner is null then return jsonb_build_object('success', false, 'reason', 'UNAUTHORIZED'); end if;
  if p_public and exists (
    select 1 from public."Links" l
    where l.owner_id = v_owner and trim(l.code) = p_code
      and coalesce((to_jsonb(l)->>'admin_publication_blocked')::boolean, false)
  ) then
    return jsonb_build_object('success', false, 'reason', 'PUBLICATION_BLOCKED_BY_ADMIN');
  end if;
  update public."Find" set visibility = case when p_public then 'Public' else 'Private' end,
    link_status = case when p_public then 'Active' else 'Disabled' end,
    link_publication_date = case when p_public then coalesce(link_publication_date, now()) else link_publication_date end
