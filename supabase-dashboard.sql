create or replace function public.dashboard_change_password(
  p_session_token text,
  p_new_password text,
  p_confirm_password text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_owner text := public.dashboard_session_owner(p_session_token);
  v_current_hash text;
  v_session_hash text;
begin
  if v_owner is null then
    return jsonb_build_object('success', false, 'reason', 'UNAUTHORIZED');
  end if;

  if p_new_password is null
     or char_length(p_new_password) < 8
     or octet_length(p_new_password) > 72 then
    return jsonb_build_object('success', false, 'reason', 'INVALID_PASSWORD');
  end if;

  if p_new_password is distinct from p_confirm_password then
    return jsonb_build_object('success', false, 'reason', 'PASSWORD_MISMATCH');
  end if;

  select password into v_current_hash
  from public."Members"
  where owner_id = v_owner
  for update;

  if not found then
    return jsonb_build_object('success', false, 'reason', 'MEMBER_NOT_FOUND');
  end if;

  if v_current_hash = crypt(p_new_password, v_current_hash) then
    return jsonb_build_object('success', false, 'reason', 'PASSWORD_UNCHANGED');
  end if;

  update public."Members"
  set password = crypt(p_new_password, gen_salt('bf', 12))
  where owner_id = v_owner;

  -- Keep the session that authorized this change and revoke every other one.
  v_session_hash := encode(digest(p_session_token, 'sha256'), 'hex');
  delete from public."MemberSessions"
  where owner_id = v_owner and token_hash <> v_session_hash;

  delete from public."MemberLoginAttempts"
  where normalized_email = (select lower(email) from public."Members" where owner_id = v_owner);

  return jsonb_build_object('success', true);
end;
$$;

