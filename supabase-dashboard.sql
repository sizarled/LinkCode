-- Public link search ---------------------------------------------------------
create or replace function public.dashboard_search_links(
  p_session_token text,
  p_query text default '',
  p_sort text default 'trending'
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_owner text := public.dashboard_session_owner(p_session_token);
  v_query text := trim(coalesce(p_query, ''));
  v_result jsonb;
begin
  if v_owner is null then return jsonb_build_object('success', false, 'reason', 'UNAUTHORIZED'); end if;

  with matches as (
    select f.*, p.username, p.avatar_url, l.destination_link
    from public."Find" f
    join public."Links" l on trim(l.code) = trim(f.code)
    left join public."Profiles" p on p.id = f.owner_id
    where f.visibility = 'Public'
      and f.link_status = 'Active'
      and l.code_status = 'Active'
      and (l.link_expiration_date is null or l.link_expiration_date > now())
      and not exists(select 1 from public."MemberBlocks" b where b.block_scope='Full' and ((b.blocker_id=f.owner_id and b.blocked_id=v_owner)or(b.blocker_id=v_owner and b.blocked_id=f.owner_id)))
      and (
        v_query = '' or f.link_title ilike '%' || v_query || '%'
        or trim(f.link_description) ilike '%' || v_query || '%'
        or coalesce(f.link_tags, '') ilike '%' || v_query || '%'
      )
    order by
      case when p_sort = 'trending' then
        (coalesce(f.visits, 0) * 3 + coalesce(f.clicks, 0) * 2 + coalesce(f.images, 0) * 0.10)
      end desc,
      case when p_sort = 'title_asc' then lower(f.link_title) end asc,
      case when p_sort = 'title_desc' then lower(f.link_title) end desc,
      case when p_sort = 'publication_oldest' then f.link_publication_date end asc,
      case when p_sort = 'creation_newest' then f.link_creation_date end desc,
      case when p_sort = 'level_desc' then f.link_level end desc,
      case when p_sort = 'visits_desc' then f.visits end desc,
      f.link_publication_date desc nulls last
    limit 60
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'owner_id', m.owner_id, 'code', trim(m.code), 'title', m.link_title,
    'description', trim(m.link_description), 'tags', m.link_tags,
    'waiting_time', m.waiting_time, 'link_level', m.link_level,
    'publisher_bonus', m.publisher_bonus, 'publisher_bonus_percentage', m.publisher_bonus_percentage,
    'creation_date', m.link_creation_date, 'publication_date', m.link_publication_date,
    'thumbnail_url', m.thumbnail_url, 'impressions', m.images,
    'clicks', m.clicks, 'visits', m.visits,
    'publisher_username', coalesce(m.username, m.owner_id), 'publisher_avatar', m.avatar_url
  )), '[]'::jsonb) into v_result from matches m;

  -- Each returned search card counts as one public-link impression.
  update public."Find" f
  set images = f.images + 1
  where trim(f.code) in (
    select item->>'code' from jsonb_array_elements(v_result) item
  );

  return jsonb_build_object('success', true, 'results', v_result);
end;
$$;

