-- Public homepage discovery; returns 50 public links per page ----------------
drop function if exists public.public_search_links(text,text);
create or replace function public.public_search_links(
  p_query text default '',
  p_sort text default 'trending',
  p_page integer default 1
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_query text := trim(coalesce(p_query,''));
  v_page integer := greatest(coalesce(p_page,1),1);
  v_page_size integer := 50;
  v_total bigint := 0;
  v_total_pages integer := 0;
  v_result jsonb;
begin
  select count(*) into v_total
  from public."Find"f
  join public."Links"l on trim(l.code)=trim(f.code)
  where f.visibility='Public'and f.link_status='Active'and l.code_status='Active'
    and coalesce((to_jsonb(l)->>'admin_publication_blocked')::boolean,false)=false
    and(l.link_expiration_date is null or l.link_expiration_date>now())
    and(v_query=''or f.link_title ilike'%'||v_query||'%'or trim(f.link_description)ilike'%'||v_query||'%'or coalesce(f.link_tags,'')ilike'%'||v_query||'%');

  v_total_pages := case when v_total=0 then 0 else ceil(v_total::numeric/v_page_size)::integer end;
  if v_total_pages>0 then v_page:=least(v_page,v_total_pages);end if;

  with matches as (
    select f.*,p.username,p.avatar_url,l.number_of_visits
    from public."Find"f
    join public."Links"l on trim(l.code)=trim(f.code)
    left join public."Profiles"p on p.id=f.owner_id
    where f.visibility='Public'and f.link_status='Active'and l.code_status='Active'
      and coalesce((to_jsonb(l)->>'admin_publication_blocked')::boolean,false)=false
      and(l.link_expiration_date is null or l.link_expiration_date>now())
      and(v_query=''or f.link_title ilike'%'||v_query||'%'or trim(f.link_description)ilike'%'||v_query||'%'or coalesce(f.link_tags,'')ilike'%'||v_query||'%')
    order by
      case when p_sort='trending'then(coalesce(f.visits,0)*3+coalesce(f.clicks,0)*2+coalesce(f.images,0)*0.10)end desc,
      case when p_sort='newest'then f.link_publication_date end desc,
      case when p_sort='title'then lower(f.link_title)end asc,
      case when p_sort='level'then f.link_level end desc,
      case when p_sort='visits'then coalesce(l.number_of_visits,f.visits)end desc,
      f.link_publication_date desc nulls last
    limit v_page_size offset((v_page-1)*v_page_size)
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'owner_id',m.owner_id,'publisher_username',coalesce(m.username,m.owner_id),'publisher_avatar',m.avatar_url,
    'code',trim(m.code),'title',m.link_title,'description',trim(m.link_description),'tags',m.link_tags,
    'waiting_time',m.waiting_time,'link_level',m.link_level,'publisher_bonus',m.publisher_bonus,
    'publisher_bonus_percentage',m.publisher_bonus_percentage,'creation_date',m.link_creation_date,
    'publication_date',m.link_publication_date,'thumbnail_url',m.thumbnail_url,
    'impressions',m.images,'clicks',m.clicks,'visits',coalesce(m.number_of_visits,m.visits)
  )),'[]'::jsonb)into v_result from matches m;

  update public."Find"f set images=f.images+1
  where trim(f.code)in(select item->>'code'from jsonb_array_elements(v_result)item);

  return jsonb_build_object(
    'success',true,
    'results',v_result,
    'page',v_page,
    'page_size',v_page_size,
    'total_results',v_total,
    'total_pages',v_total_pages
  );
end;$$;
