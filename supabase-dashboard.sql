-- Keep the unified Profiles row synchronized with Members ------------------
create or replace function public.sync_member_to_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_status text;
begin
  v_profile_status := case new.account_status
    when 'Active' then 'Active'
    when 'Banned' then 'Banned'
    else 'Inactive'
  end;

  insert into public."Profiles" (id, username, full_name, email, number_of_followers, profile_status, joined_date)
  values (
    new.owner_id,
    'member_' || lower(new.owner_id),
    new.full_name,
    lower(new.email),
    0,
    v_profile_status,
    new.joining_date
  )
  on conflict (id) do update set
    full_name = excluded.full_name,
    email = excluded.email,
    profile_status = excluded.profile_status,
    joined_date = excluded.joined_date,
    updated_at = now();

  return new;
end;
$$;

drop trigger if exists members_sync_profile_trigger on public."Members";
create trigger members_sync_profile_trigger
after insert or update of full_name, email, account_status
on public."Members"
for each row execute function public.sync_member_to_profile();

-- Keep the cached follower count synchronized with Follows ------------------
create or replace function public.sync_profile_follower_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile_id text;
begin
  v_profile_id := case when tg_op = 'DELETE' then old.following_id else new.following_id end;
  update public."Profiles"
  set number_of_followers = (
    select count(*) from public."Follows" f where f.following_id = v_profile_id
  ), updated_at = now()
  where id = v_profile_id;

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

drop trigger if exists follows_sync_profile_count_trigger on public."Follows";
create trigger follows_sync_profile_count_trigger
after insert or delete on public."Follows"
for each row execute function public.sync_profile_follower_count();

