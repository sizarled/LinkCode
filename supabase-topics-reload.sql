-- ============================================================================
-- LINKCODE — TOPICS: RELOAD + VERIFY
-- ----------------------------------------------------------------------------
-- Use this after running supabase-topics.sql (or when you see the error:
--   "Could not find the function public.dashboard_publish_link(...) in the
--    schema cache").
--
-- Why the error happens:
--   • The new dashboard_publish_link (which accepts p_topics text[]) has not
--     been created yet, OR
--   • It was created but PostgREST is still using an old schema cache.
--
-- Steps (run this whole file in the SQL Editor, then press F5 / run again):
--   1) It drops the old p_tags function and creates the new p_topics one.
--   2) It clears the PostgREST schema cache (notify pgrst).
--   3) The final query lists the LinkCode functions — check that
--      dashboard_publish_link shows "p_topics text[]" as its last argument.
-- ----------------------------------------------------------------------------

drop function if exists public.dashboard_publish_link(text, text, text, text, text, text);

do $do$
begin
  if not exists (
    select 1 from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname = 'dashboard_publish_link'
      and pg_get_function_identity_arguments(p.oid) like '%p_topics text[]%'
  ) then
    -- Topics tables (created if missing) — required by the new function.
    create table if not exists public."Topics" (
      id bigint generated by default as identity primary key,
      topic_name text not null,
      topic_slug text not null unique,
      usage_count bigint not null default 0,
      created_by text,
      created_at timestamp with time zone not null default now(),
      constraint topics_name_length check (char_length(topic_name) between 2 and 40),
      constraint topics_slug_length check (char_length(topic_slug) between 2 and 40),
      constraint topics_usage_non_negative check (usage_count >= 0)
    );

    create table if not exists public."LinkTopics" (
      link_id bigint not null references public."Links" (id) on delete cascade,
      topic_id bigint not null references public."Topics" (id) on delete cascade,
      added_at timestamp with time zone not null default now(),
      constraint LinkTopics_pkey primary key (link_id, topic_id)
    );

    create index if not exists linktopics_topic_idx on public."LinkTopics" (topic_id);

    create or replace function public.dashboard_publish_link(
      p_session_token text,
      p_code text,
      p_title text,
      p_description text,
      p_thumbnail_url text,
      p_topics text[] default null
    )
    returns jsonb
    language plpgsql
    security definer
    set search_path = public, extensions
    as $fn$
    declare
      v_owner text := public.dashboard_session_owner(p_session_token);
      v_link public."Links"%rowtype;
      v_title text := trim(coalesce(p_title,''));
      v_description text := trim(coalesce(p_description,''));
      v_topic_names text[];
      v_topic_name text;
      v_topic_id bigint;
      v_topic_ids bigint[] := '{}';
      v_old_topic_ids bigint[];
    begin
      if v_owner is null then return jsonb_build_object('success', false, 'reason', 'UNAUTHORIZED'); end if;
      select * into v_link from public."Links" where owner_id = v_owner and trim(code) = p_code limit 1;
      if not found then return jsonb_build_object('success', false, 'reason', 'LINK_NOT_FOUND'); end if;
      if coalesce((to_jsonb(v_link)->>'admin_publication_blocked')::boolean, false) then
        return jsonb_build_object('success', false, 'reason', 'PUBLICATION_BLOCKED_BY_ADMIN');
      end if;
      if char_length(v_title) < 3 or char_length(v_title) > 120 then return jsonb_build_object('success', false, 'reason', 'INVALID_TITLE'); end if;
      if char_length(v_description) < 10 or char_length(v_description) > 190 then return jsonb_build_object('success', false, 'reason', 'INVALID_DESCRIPTION'); end if;
      if p_thumbnail_url is not null and trim(p_thumbnail_url) <> '' and trim(p_thumbnail_url) !~* '^https?://[^[:space:]]+$' then return jsonb_build_object('success', false, 'reason', 'INVALID_THUMBNAIL'); end if;

      select coalesce(array_agg(x), '{}'::text[]) into v_topic_names
      from (
        select distinct trim(regexp_replace(t, '\s+', ' ', 'g')) as x
        from unnest(coalesce(p_topics, '{}'::text[])) as t
        where trim(coalesce(t, '')) <> ''
      ) q
      where char_length(x) between 2 and 40;

      if coalesce(cardinality(v_topic_names), 0) < 1 then
        return jsonb_build_object('success', false, 'reason', 'TOPICS_REQUIRED');
      end if;
      if cardinality(v_topic_names) > 5 then
        return jsonb_build_object('success', false, 'reason', 'TOPICS_TOO_MANY');
      end if;

      foreach v_topic_name in array v_topic_names loop
        insert into public."Topics" (topic_name, topic_slug, created_by)
        values (v_topic_name, lower(v_topic_name), v_owner)
        on conflict (topic_slug) do update set topic_name = excluded.topic_name
        returning id into v_topic_id;
        v_topic_ids := v_topic_ids || v_topic_id;
      end loop;

      select coalesce(array_agg(lt.topic_id), '{}'::bigint[]) into v_old_topic_ids
      from public."LinkTopics" lt where lt.link_id = v_link.id;

      delete from public."LinkTopics" where link_id = v_link.id;
      insert into public."LinkTopics" (link_id, topic_id)
      select v_link.id, x from unnest(v_topic_ids) as x
      on conflict do nothing;

      update public."Topics" t
      set usage_count = (select count(*) from public."LinkTopics" lt where lt.topic_id = t.id)
      where t.id = any(v_topic_ids) or t.id = any(v_old_topic_ids);

      insert into public."Find" (
        owner_id, code, link_title, link_description, link_tags, waiting_time,
        link_level, link_status, publisher_bonus, link_creation_date,
        link_expiration_date, link_publication_date, publisher_bonus_percentage,
        thumbnail_url, visibility
      ) values (
        v_owner, trim(v_link.code), v_title, v_description, array_to_string(v_topic_names, ','),
        v_link.waiting_time, v_link.link_level, 'Active', v_link.publisher_bonus_status,
        v_link.link_creation_date, v_link.link_expiration_date, now(),
        v_link.publisher_bonus_percentage, nullif(trim(p_thumbnail_url),''), 'Public'
      )
      on conflict (code) do update set
        link_title = excluded.link_title,
        link_description = excluded.link_description,
        link_tags = excluded.link_tags,
        waiting_time = excluded.waiting_time,
        link_level = excluded.link_level,
        link_status = 'Active',
        publisher_bonus = excluded.publisher_bonus,
        link_expiration_date = excluded.link_expiration_date,
        link_publication_date = coalesce(public."Find".link_publication_date, now()),
        publisher_bonus_percentage = excluded.publisher_bonus_percentage,
        thumbnail_url = excluded.thumbnail_url,
        visibility = 'Public';

      return jsonb_build_object('success', true, 'code', p_code, 'visibility', 'Public', 'topics', v_topic_names);
    end;
    $fn$;

    grant execute on function public.dashboard_publish_link(text, text, text, text, text, text[]) to anon, authenticated;
    raise notice 'dashboard_publish_link (p_topics) has been created.';
  else
    raise notice 'dashboard_publish_link (p_topics) already exists.';
  end if;
end;
$do$;

-- Autocomplete RPC (topics appear as you type the first letters) ---------------
create or replace function public.topics_autocomplete(
  p_prefix text default '',
  p_limit integer default 8
)
returns jsonb
language sql
security definer
set search_path = public, extensions
as $sql$
  select jsonb_build_object(
    'success', true,
    'topics', coalesce((
      select jsonb_agg(jsonb_build_object('id', t.id, 'topic_name', t.topic_name, 'usage_count', t.usage_count))
      from (
        select t.id, t.topic_name, t.usage_count
        from public."Topics" t
        where trim(coalesce(p_prefix, '')) = '' or t.topic_name ilike trim(p_prefix) || '%'
        order by t.usage_count desc, t.topic_name asc
        limit least(greatest(coalesce(p_limit, 8), 1), 20)
      ) t
    ), '[]'::jsonb)
  );
$sql$;

revoke all on function public.topics_autocomplete(text, integer) from public;
grant execute on function public.topics_autocomplete(text, integer) to anon, authenticated;

-- IMPORTANT: reload the PostgREST schema cache (fixes the "schema cache" error)
notify pgrst, 'reload schema';

-- VERIFY: dashboard_publish_link must end with "p_topics text[]" ---------------
select
  n.nspname as schema,
  p.proname as function_name,
  pg_get_function_identity_arguments(p.oid) as arguments
from pg_proc p
join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public'
  and p.proname in ('dashboard_publish_link', 'topics_autocomplete')
order by p.proname;
