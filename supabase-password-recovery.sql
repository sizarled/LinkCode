-- LinkCode password recovery for recovry.html
-- Run this file once in the Supabase SQL Editor after creating public."Members".
-- Recovery uses a short-lived, one-time token; the password is never updated directly by the browser.

create extension if not exists pgcrypto with schema extensions;

alter table public."Members" enable row level security;

create table if not exists public."MemberPasswordResetAttempts" (
  id bigint generated by default as identity primary key,
  owner_id_input text not null,
  normalized_email text not null,
  requester_ip inet null,
  succeeded boolean not null default false,
  attempted_at timestamp with time zone not null default now()
);

create index if not exists member_password_reset_attempts_lookup_idx
on public."MemberPasswordResetAttempts" (normalized_email, attempted_at desc);

create table if not exists public."MemberPasswordResets" (
  reset_id uuid primary key default gen_random_uuid(),
  owner_id text not null references public."Members" (owner_id) on delete cascade,
  token_hash text not null unique,
  requester_ip inet null,
  created_at timestamp with time zone not null default now(),
  expires_at timestamp with time zone not null,
  used boolean not null default false,
  used_at timestamp with time zone null
);

create index if not exists member_password_resets_owner_idx
on public."MemberPasswordResets" (owner_id, expires_at desc);

alter table public."MemberPasswordResetAttempts" enable row level security;
alter table public."MemberPasswordResets" enable row level security;

revoke all on table public."MemberPasswordResetAttempts" from anon, authenticated;
revoke all on table public."MemberPasswordResets" from anon, authenticated;

create or replace function public.request_member_password_reset(
  p_owner_number text,
  p_email text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_owner_number text := trim(coalesce(p_owner_number, ''));
  v_owner_id text;
  v_email text := lower(trim(coalesce(p_email, '')));
  v_member public."Members"%rowtype;
  v_headers jsonb := coalesce(nullif(current_setting('request.headers', true), '')::jsonb, '{}'::jsonb);
  v_forwarded text;
  v_ip inet;
  v_failed_count integer := 0;
  v_token text;
  v_token_hash text;
begin
  if v_owner_number !~ '^[0-9]+$' or char_length(v_owner_number) > 30 then
    return jsonb_build_object('success', false, 'reason', 'INVALID_MEMBER_ID');
  end if;
  v_owner_id := 'ID' || v_owner_number;

  if char_length(v_email) > 254
     or v_email !~* '^[A-Z0-9._%+\-]+@[A-Z0-9.\-]+\.[A-Z]{2,}$' then
    return jsonb_build_object('success', false, 'reason', 'INVALID_EMAIL');
  end if;

  v_forwarded := split_part(coalesce(v_headers->>'x-forwarded-for', v_headers->>'x-real-ip', ''), ',', 1);
  begin
    v_ip := nullif(trim(v_forwarded), '')::inet;
  exception when others then
    v_ip := null;
  end;

  perform pg_advisory_xact_lock(hashtext('member-recovery:' || v_owner_id || ':' || v_email));

  select count(*)::integer into v_failed_count
  from public."MemberPasswordResetAttempts"
  where normalized_email = v_email
    and succeeded = false
    and attempted_at >= now() - interval '30 minutes'
    and (v_ip is null or requester_ip = v_ip);

  if v_failed_count >= 5 then
    return jsonb_build_object(
      'success', false,
      'reason', 'RATE_LIMITED',
      'retry_after_seconds', 1800
    );
  end if;

  select * into v_member
  from public."Members"
  where owner_id = v_owner_id
    and lower(email) = v_email
  limit 1;

  if not found then
    insert into public."MemberPasswordResetAttempts" (
      owner_id_input, normalized_email, requester_ip, succeeded
    ) values (v_owner_id, v_email, v_ip, false);

    return jsonb_build_object('success', false, 'reason', 'DETAILS_MISMATCH');
  end if;

  insert into public."MemberPasswordResetAttempts" (
    owner_id_input, normalized_email, requester_ip, succeeded
  ) values (v_owner_id, v_email, v_ip, true);

  -- Invalidate older unused tokens for this account.
  update public."MemberPasswordResets"
  set used = true,
      used_at = now()
  where owner_id = v_owner_id
    and used = false;

  v_token := encode(gen_random_bytes(32), 'hex');
  v_token_hash := encode(digest(v_token, 'sha256'), 'hex');

  insert into public."MemberPasswordResets" (
    owner_id,
    token_hash,
    requester_ip,
    expires_at
  ) values (
    v_owner_id,
    v_token_hash,
    v_ip,
    now() + interval '10 minutes'
  );

  delete from public."MemberPasswordResetAttempts"
  where attempted_at < now() - interval '30 days';

  return jsonb_build_object(
    'success', true,
    'reset_token', v_token,
    'expires_in_seconds', 600,
    'owner_id', v_owner_id
  );
end;
$$;

revoke all on function public.request_member_password_reset(text, text) from public;
grant execute on function public.request_member_password_reset(text, text) to anon, authenticated;

create or replace function public.complete_member_password_reset(
  p_reset_token text,
  p_new_password text,
  p_confirm_password text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_token_hash text;
  v_reset public."MemberPasswordResets"%rowtype;
  v_current_hash text;
  v_member_email text;
begin
  if p_reset_token is null or p_reset_token !~ '^[a-f0-9]{64}$' then
    return jsonb_build_object('success', false, 'reason', 'RESET_INVALID');
  end if;

  if p_new_password is null
     or char_length(p_new_password) < 8
     or octet_length(p_new_password) > 72 then
    return jsonb_build_object('success', false, 'reason', 'INVALID_PASSWORD');
  end if;

  if p_new_password is distinct from p_confirm_password then
    return jsonb_build_object('success', false, 'reason', 'PASSWORD_MISMATCH');
  end if;

  v_token_hash := encode(digest(p_reset_token, 'sha256'), 'hex');

  select * into v_reset
  from public."MemberPasswordResets"
  where token_hash = v_token_hash
  for update;

  if not found or v_reset.used then
    return jsonb_build_object('success', false, 'reason', 'RESET_INVALID');
  end if;

  if v_reset.expires_at <= now() then
    update public."MemberPasswordResets"
    set used = true, used_at = now()
    where reset_id = v_reset.reset_id;
    return jsonb_build_object('success', false, 'reason', 'RESET_EXPIRED');
  end if;

  select password, email into v_current_hash, v_member_email
  from public."Members"
  where owner_id = v_reset.owner_id
  for update;

  if not found then
    return jsonb_build_object('success', false, 'reason', 'MEMBER_NOT_FOUND');
  end if;

  if v_current_hash = crypt(p_new_password, v_current_hash) then
    return jsonb_build_object('success', false, 'reason', 'PASSWORD_UNCHANGED');
  end if;

  update public."Members"
  set password = crypt(p_new_password, gen_salt('bf', 12))
  where owner_id = v_reset.owner_id;

  update public."MemberPasswordResets"
  set used = true,
      used_at = now()
  where reset_id = v_reset.reset_id;

  -- Revoke all browser sessions and clear failed login attempts if the login tables exist.
  if to_regclass('public."MemberSessions"') is not null then
    execute 'delete from public."MemberSessions" where owner_id = $1'
    using v_reset.owner_id;
  end if;

  if to_regclass('public."MemberLoginAttempts"') is not null then
    execute 'delete from public."MemberLoginAttempts" where normalized_email = $1'
    using lower(v_member_email);
  end if;

  return jsonb_build_object(
    'success', true,
    'owner_id', v_reset.owner_id
  );
end;
$$;

revoke all on function public.complete_member_password_reset(text, text, text) from public;
grant execute on function public.complete_member_password_reset(text, text, text) to anon, authenticated;

-- Recovery tables and Members remain inaccessible through direct anonymous REST queries.
revoke select, insert, update, delete on table public."Members" from anon;
