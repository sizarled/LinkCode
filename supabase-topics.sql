-- ============================================================================
-- LINKCODE — TOPICS SYSTEM (replaces free-text tags)
-- ----------------------------------------------------------------------------
-- Run this file in the Supabase SQL Editor AFTER supabase-dashboard.sql.
--
-- New storage:
--   Topics      : every topic ever created (autocomplete source)
--   LinkTopics  : which topics belong to which link (1-5 per link)
--
-- New RPC:
--   topics_autocomplete(p_prefix, p_limit)
--     Existing topics appear as soon as the first letters are typed.
--     Empty prefix returns the most-used topics.  (used by the publish form)
--
-- Replaced RPCs:
--   dashboard_publish_link(..., p_topics text[])   (was p_tags text)
--   dashboard_search_links(...)   -> searches topics, returns 'topics' array
--   public_search_links(...)      -> searches topics, returns 'topics' array
--   public_profile_get(...)       -> returns 'topics' on links & posts
--
-- Legacy comma-separated link_tags are migrated into real topics below
-- (safe to re-run, existing links keep working everywhere).
-- ============================================================================

-- LinkCode Topics -------------------------------------------------------------
-- First-class topics (replaces free-text tags): each public link carries 1-5
-- topics. Typing the first letters of a topic autocompletes existing topics.
create table if not exists public."Topics" (
  id bigint generated by default as identity primary key,
  topic_name text not null,
  topic_slug text not null unique,
  usage_count bigint not null default 0,
  created_by text,
  created_at timestamp with time zone not null default now(),
  constraint topics_name_length check (char_length(topic_name) between 2 and 40),
  constraint topics_slug_length check (char_length(topic_slug) between 2 and 40),
  constraint topics_usage_non_negative check (usage_count >= 0)
);

create table if not exists public."LinkTopics" (
  link_id bigint not null references public."Links" (id) on delete cascade,
  topic_id bigint not null references public."Topics" (id) on delete cascade,
  added_at timestamp with time zone not null default now(),
  constraint LinkTopics_pkey primary key (link_id, topic_id)
);

create index if not exists linktopics_topic_idx on public."LinkTopics" (topic_id);

-- Migrate legacy comma-separated link_tags into real topics (safe to re-run).
insert into public."Topics" (topic_name, topic_slug, usage_count)
select trim(x.topic), lower(trim(x.topic)), count(*)
from public."Find" f
cross join lateral unnest(string_to_array(coalesce(f.link_tags, ''), ',')) as x(topic)
where trim(x.topic) <> '' and char_length(trim(x.topic)) between 2 and 40
group by trim(x.topic)
on conflict (topic_slug) do update
  set usage_count = public."Topics".usage_count + excluded.usage_count;

insert into public."LinkTopics" (link_id, topic_id)
select distinct l.id, t.id
from public."Find" f
join public."Links" l on trim(l.code) = trim(f.code)
cross join lateral unnest(string_to_array(coalesce(f.link_tags, ''), ',')) as x(topic)
join public."Topics" t on t.topic_slug = lower(trim(x.topic))
where trim(x.topic) <> ''
on conflict (link_id, topic_id) do nothing;

-- Topic autocomplete: existing topics appear as soon as the first letters are
-- typed (empty prefix returns the most popular topics).
create or replace function public.topics_autocomplete(
  p_prefix text default '',
  p_limit integer default 8
)
returns jsonb
language sql
security definer
set search_path = public, extensions
as $$
  select jsonb_build_object(
    'success', true,
    'topics', coalesce((
      select jsonb_agg(jsonb_build_object('id', t.id, 'topic_name', t.topic_name, 'usage_count', t.usage_count))
      from (
        select t.id, t.topic_name, t.usage_count
        from public."Topics" t
        where trim(coalesce(p_prefix, '')) = '' or t.topic_name ilike trim(p_prefix) || '%'
        order by t.usage_count desc, t.topic_name asc
        limit least(greatest(coalesce(p_limit, 8), 1), 20)
      ) t
    ), '[]'::jsonb)
  );
$$;

revoke all on function public.topics_autocomplete(text, integer) from public;
grant execute on function public.topics_autocomplete(text, integer) to anon, authenticated;

drop function if exists public.dashboard_publish_link(text, text, text, text, text, text);
create or replace function public.dashboard_publish_link(
  p_session_token text,
  p_code text,
  p_title text,
  p_description text,
  p_thumbnail_url text,
  p_topics text[] default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_owner text := public.dashboard_session_owner(p_session_token);
  v_link public."Links"%rowtype;
  v_title text := trim(coalesce(p_title,''));
  v_description text := trim(coalesce(p_description,''));
  v_topic_names text[];
  v_topic_name text;
  v_topic_id bigint;
  v_topic_ids bigint[] := '{}';
  v_old_topic_ids bigint[];
begin
  if v_owner is null then return jsonb_build_object('success', false, 'reason', 'UNAUTHORIZED'); end if;
  select * into v_link from public."Links" where owner_id = v_owner and trim(code) = p_code limit 1;
  if not found then return jsonb_build_object('success', false, 'reason', 'LINK_NOT_FOUND'); end if;
  if coalesce((to_jsonb(v_link)->>'admin_publication_blocked')::boolean, false) then
    return jsonb_build_object('success', false, 'reason', 'PUBLICATION_BLOCKED_BY_ADMIN');
  end if;
  if char_length(v_title) < 3 or char_length(v_title) > 120 then return jsonb_build_object('success', false, 'reason', 'INVALID_TITLE'); end if;
  if char_length(v_description) < 10 or char_length(v_description) > 190 then return jsonb_build_object('success', false, 'reason', 'INVALID_DESCRIPTION'); end if;
  if p_thumbnail_url is not null and trim(p_thumbnail_url) <> '' and trim(p_thumbnail_url) !~* '^https?://[^[:space:]]+$' then return jsonb_build_object('success', false, 'reason', 'INVALID_THUMBNAIL'); end if;

  -- Normalize topic names: trim, collapse whitespace, de-duplicate, drop empties.
  select coalesce(array_agg(x), '{}'::text[]) into v_topic_names
  from (
    select distinct trim(regexp_replace(t, '\\s+', ' ', 'g')) as x
    from unnest(coalesce(p_topics, '{}'::text[])) as t
    where trim(coalesce(t, '')) <> ''
  ) q
  where char_length(x) between 2 and 40;

  if coalesce(cardinality(v_topic_names), 0) < 1 then
    return jsonb_build_object('success', false, 'reason', 'TOPICS_REQUIRED');
  end if;
  if cardinality(v_topic_names) > 5 then
    return jsonb_build_object('success', false, 'reason', 'TOPICS_TOO_MANY');
  end if;

  -- Insert or reuse topics (case-insensitive via topic_slug) and collect ids.
  foreach v_topic_name in array v_topic_names loop
    insert into public."Topics" (topic_name, topic_slug, created_by)
    values (v_topic_name, lower(v_topic_name), v_owner)
    on conflict (topic_slug) do update set topic_name = excluded.topic_name
    returning id into v_topic_id;
    v_topic_ids := v_topic_ids || v_topic_id;
  end loop;

  -- Remember previously linked topics so their usage counts are refreshed.
  select coalesce(array_agg(lt.topic_id), '{}'::bigint[]) into v_old_topic_ids
  from public."LinkTopics" lt where lt.link_id = v_link.id;

  delete from public."LinkTopics" where link_id = v_link.id;
  insert into public."LinkTopics" (link_id, topic_id)
  select v_link.id, x from unnest(v_topic_ids) as x
  on conflict do nothing;

  update public."Topics" t
  set usage_count = (select count(*) from public."LinkTopics" lt where lt.topic_id = t.id)
  where t.id = any(v_topic_ids) or t.id = any(v_old_topic_ids);

  insert into public."Find" (
    owner_id, code, link_title, link_description, link_tags, waiting_time,
    link_level, link_status, publisher_bonus, link_creation_date,
    link_expiration_date, link_publication_date, publisher_bonus_percentage,
    thumbnail_url, visibility
  ) values (
    v_owner, trim(v_link.code), v_title, v_description, array_to_string(v_topic_names, ','),
    v_link.waiting_time, v_link.link_level, 'Active', v_link.publisher_bonus_status,
    v_link.link_creation_date, v_link.link_expiration_date, now(),
    v_link.publisher_bonus_percentage, nullif(trim(p_thumbnail_url),''), 'Public'
  )
  on conflict (code) do update set
    link_title = excluded.link_title,
    link_description = excluded.link_description,
    link_tags = excluded.link_tags,
    waiting_time = excluded.waiting_time,
    link_level = excluded.link_level,
    link_status = 'Active',
    publisher_bonus = excluded.publisher_bonus,
    link_expiration_date = excluded.link_expiration_date,
    link_publication_date = coalesce(public."Find".link_publication_date, now()),
    publisher_bonus_percentage = excluded.publisher_bonus_percentage,
    thumbnail_url = excluded.thumbnail_url,
    visibility = 'Public';

  return jsonb_build_object('success', true, 'code', p_code, 'visibility', 'Public', 'topics', v_topic_names);
end;
$$;

revoke all on function public.dashboard_publish_link(text, text, text, text, text, text[]) from public;
grant execute on function public.dashboard_publish_link(text, text, text, text, text, text[]) to anon, authenticated;

create or replace function public.dashboard_search_links(
  p_session_token text,
  p_query text default '',
  p_sort text default 'trending'
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_owner text := public.dashboard_session_owner(p_session_token);
  v_query text := trim(coalesce(p_query, ''));
  v_result jsonb;
begin
  if v_owner is null then return jsonb_build_object('success', false, 'reason', 'UNAUTHORIZED'); end if;

  with matches as (
    select f.*, l.id as link_id, p.username, p.avatar_url, l.destination_link
    from public."Find" f
    join public."Links" l on trim(l.code) = trim(f.code)
    left join public."Profiles" p on p.id = f.owner_id
    where f.visibility = 'Public'
      and f.link_status = 'Active'
      and l.code_status = 'Active'
      and (l.link_expiration_date is null or l.link_expiration_date > now())
      and not exists(select 1 from public."MemberBlocks" b where b.block_scope='Full' and ((b.blocker_id=f.owner_id and b.blocked_id=v_owner)or(b.blocker_id=v_owner and b.blocked_id=f.owner_id)))
      and (
        v_query = '' or f.link_title ilike '%' || v_query || '%'
        or trim(f.link_description) ilike '%' || v_query || '%'
        or coalesce(f.link_tags, '') ilike '%' || v_query || '%'
        or exists(
          select 1 from public."LinkTopics" lt
          join public."Topics" t on t.id = lt.topic_id
          where lt.link_id = l.id and t.topic_name ilike '%' || v_query || '%'
        )
      )
    order by
      case when p_sort = 'trending' then
        (coalesce(f.visits, 0) * 3 + coalesce(f.clicks, 0) * 2 + coalesce(f.images, 0) * 0.10)
      end desc,
      case when p_sort = 'title_asc' then lower(f.link_title) end asc,
      case when p_sort = 'title_desc' then lower(f.link_title) end desc,
      case when p_sort = 'publication_oldest' then f.link_publication_date end asc,
      case when p_sort = 'creation_newest' then f.link_creation_date end desc,
      case when p_sort = 'level_desc' then f.link_level end desc,
      case when p_sort = 'visits_desc' then f.visits end desc,
      f.link_publication_date desc nulls last
    limit 60
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'owner_id', m.owner_id, 'code', trim(m.code), 'title', m.link_title,
    'description', trim(m.link_description), 'tags', m.link_tags,
    'topics', coalesce((
      select jsonb_agg(t.topic_name order by t.topic_name)
      from public."LinkTopics" lt join public."Topics" t on t.id = lt.topic_id
      where lt.link_id = m.link_id
    ), '[]'::jsonb),
    'waiting_time', m.waiting_time, 'link_level', m.link_level,
    'publisher_bonus', m.publisher_bonus, 'publisher_bonus_percentage', m.publisher_bonus_percentage,
    'creation_date', m.link_creation_date, 'publication_date', m.link_publication_date,
    'thumbnail_url', m.thumbnail_url, 'impressions', m.images,
    'clicks', m.clicks, 'visits', m.visits,
    'publisher_username', coalesce(m.username, m.owner_id), 'publisher_avatar', m.avatar_url
  )), '[]'::jsonb) into v_result from matches m;

  -- Each returned search card counts as one public-link impression.
  update public."Find" f
  set images = f.images + 1
  where trim(f.code) in (
    select item->>'code' from jsonb_array_elements(v_result) item
  );

  return jsonb_build_object('success', true, 'results', v_result);
end;
$$;

revoke all on function public.dashboard_search_links(text, text, text) from public;
grant execute on function public.dashboard_search_links(text, text, text) to anon, authenticated;

drop function if exists public.public_search_links(text,text);
create or replace function public.public_search_links(
  p_query text default '',
  p_sort text default 'trending',
  p_page integer default 1
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_query text := trim(coalesce(p_query,''));
  v_page integer := greatest(coalesce(p_page,1),1);
  v_page_size integer := 50;
  v_total bigint := 0;
  v_total_pages integer := 0;
  v_result jsonb;
begin
  select count(*) into v_total
  from public."Find"f
  join public."Links"l on trim(l.code)=trim(f.code)
  where f.visibility='Public'and f.link_status='Active'and l.code_status='Active'
    and coalesce((to_jsonb(l)->>'admin_publication_blocked')::boolean,false)=false
    and(l.link_expiration_date is null or l.link_expiration_date>now())
    and(v_query=''or f.link_title ilike'%'||v_query||'%'or trim(f.link_description)ilike'%'||v_query||'%'or coalesce(f.link_tags,'')ilike'%'||v_query||'%'or exists(select 1 from public."LinkTopics"lt join public."Topics"t on t.id=lt.topic_id where lt.link_id=l.id and t.topic_name ilike'%'||v_query||'%'));

  v_total_pages := case when v_total=0 then 0 else ceil(v_total::numeric/v_page_size)::integer end;
  if v_total_pages>0 then v_page:=least(v_page,v_total_pages);end if;

  with matches as (
    select f.*,l.id as link_id,p.username,p.avatar_url,l.number_of_visits
    from public."Find"f
    join public."Links"l on trim(l.code)=trim(f.code)
    left join public."Profiles"p on p.id=f.owner_id
    where f.visibility='Public'and f.link_status='Active'and l.code_status='Active'
      and coalesce((to_jsonb(l)->>'admin_publication_blocked')::boolean,false)=false
      and(l.link_expiration_date is null or l.link_expiration_date>now())
      and(v_query=''or f.link_title ilike'%'||v_query||'%'or trim(f.link_description)ilike'%'||v_query||'%'or coalesce(f.link_tags,'')ilike'%'||v_query||'%'or exists(select 1 from public."LinkTopics"lt join public."Topics"t on t.id=lt.topic_id where lt.link_id=l.id and t.topic_name ilike'%'||v_query||'%'))
    order by
      case when p_sort='trending'then(coalesce(f.visits,0)*3+coalesce(f.clicks,0)*2+coalesce(f.images,0)*0.10)end desc,
      case when p_sort='newest'then f.link_publication_date end desc,
      case when p_sort='title'then lower(f.link_title)end asc,
      case when p_sort='level'then f.link_level end desc,
      case when p_sort='visits'then coalesce(l.number_of_visits,f.visits)end desc,
      f.link_publication_date desc nulls last
    limit v_page_size offset((v_page-1)*v_page_size)
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'owner_id',m.owner_id,'publisher_username',coalesce(m.username,m.owner_id),'publisher_avatar',m.avatar_url,
    'code',trim(m.code),'title',m.link_title,'description',trim(m.link_description),'tags',m.link_tags,'topics',coalesce((select jsonb_agg(t.topic_name order by t.topic_name)from public."LinkTopics"lt join public."Topics"t on t.id=lt.topic_id where lt.link_id=m.link_id),'[]'::jsonb),
    'waiting_time',m.waiting_time,'link_level',m.link_level,'publisher_bonus',m.publisher_bonus,
    'publisher_bonus_percentage',m.publisher_bonus_percentage,'creation_date',m.link_creation_date,
    'publication_date',m.link_publication_date,'thumbnail_url',m.thumbnail_url,
    'impressions',m.images,'clicks',m.clicks,'visits',coalesce(m.number_of_visits,m.visits)
  )),'[]'::jsonb)into v_result from matches m;

  update public."Find"f set images=f.images+1
  where trim(f.code)in(select item->>'code'from jsonb_array_elements(v_result)item);

  return jsonb_build_object(
    'success',true,
    'results',v_result,
    'page',v_page,
    'page_size',v_page_size,
    'total_results',v_total,
    'total_pages',v_total_pages
  );
end;$$;
revoke all on function public.public_search_links(text,text,integer) from public;
grant execute on function public.public_search_links(text,text,integer) to anon,authenticated;

create or replace function public.public_profile_get(
  p_username text,
  p_session_token text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_profile public."Profiles"%rowtype;
  v_viewer text := public.dashboard_session_owner(p_session_token);
begin
  select p.* into v_profile
  from public."Profiles" p
  join public."Members" m on m.owner_id = p.id
  where lower(p.username) = lower(trim(coalesce(p_username, '')))
    and p.profile_status = 'Active'
    and m.account_status = 'Active'
  limit 1;

  if not found then
    return jsonb_build_object('success', false, 'reason', 'PROFILE_NOT_FOUND');
  end if;
  if v_viewer is not null and exists(
    select 1 from public."MemberBlocks" b
    where b.blocker_id=v_profile.id and b.blocked_id=v_viewer and b.block_scope='Full'
  ) then
    return jsonb_build_object('success',false,'reason','PROFILE_BLOCKED');
  end if;

  return jsonb_build_object(
    'success', true,
    'profile', jsonb_build_object(
      'owner_id', v_profile.id,
      'username', v_profile.username,
      'avatar_url', v_profile.avatar_url,
      'bio', v_profile.bio,
      'joining_date', v_profile.joined_date,
      'followers', (select count(*) from public."Follows" f where f.following_id = v_profile.id),
      'following', (select count(*) from public."Follows" f where f.follower_id = v_profile.id),
      'published_links', (select count(*) from public."Find" f where f.owner_id = v_profile.id and f.visibility = 'Public' and f.link_status = 'Active'),
      'total_valid_visits', (select count(*) from public."Visits" v where v.owner_id=v_profile.id),
      'account_level', public.account_level_for_visits((select count(*) from public."Visits" v where v.owner_id=v_profile.id))
    ),
    'viewer', jsonb_build_object(
      'authenticated', v_viewer is not null,
      'is_owner', v_viewer = v_profile.id,
      'is_following', case when v_viewer is null then false else exists(
        select 1 from public."Follows" f where f.follower_id = v_viewer and f.following_id = v_profile.id
      ) end,
      'can_message', case when v_viewer is null or v_viewer=v_profile.id then false else
        exists(select 1 from public."Follows"f where f.follower_id=v_viewer and f.following_id=v_profile.id)
        and not exists(select 1 from public."MemberBlocks"b where b.blocker_id=v_profile.id and b.blocked_id=v_viewer and b.block_scope in('Messages','Full'))
        and not exists(select 1 from public."MemberBlocks"b where b.blocker_id=v_viewer and b.blocked_id=v_profile.id and b.block_scope='Full') end,
      'block_scope', case when v_viewer is null then null else(
        select b.block_scope from public."MemberBlocks"b where b.blocker_id=v_viewer and b.blocked_id=v_profile.id limit 1
      )end
    ),
    'links', coalesce((
      select jsonb_agg(jsonb_build_object(
        'code', trim(f.code), 'title', f.link_title,
        'description', trim(f.link_description), 'tags', f.link_tags,
        'topics', coalesce((select jsonb_agg(tt.topic_name order by tt.topic_name) from public."LinkTopics" lt join public."Topics" tt on tt.id = lt.topic_id where lt.link_id = l.id), '[]'::jsonb),
        'waiting_time', f.waiting_time, 'link_level', f.link_level,
        'publisher_bonus', f.publisher_bonus,
        'publisher_bonus_percentage', f.publisher_bonus_percentage,
        'creation_date', f.link_creation_date,
        'publication_date', f.link_publication_date,
        'expiration_date', f.link_expiration_date,
        'thumbnail_url', f.thumbnail_url,
        'impressions', f.images, 'clicks', f.clicks, 'visits', f.visits
      ) order by f.link_publication_date desc nulls last)
      from public."Find" f
      join public."Links" l on trim(l.code) = trim(f.code)
      where f.owner_id = v_profile.id
        and f.visibility = 'Public'
        and f.link_status = 'Active'
        and l.code_status = 'Active'
        and (l.link_expiration_date is null or l.link_expiration_date > now())
    ), '[]'::jsonb),
    'following_posts', coalesce((
      select jsonb_agg(jsonb_build_object(
        'owner_id', pub.owner_id,
        'publisher_username', coalesce(lp.username, pub.owner_id),
        'publisher_avatar', lp.avatar_url,
        'code', trim(pub.code),
        'title', pub.link_title,
        'description', trim(pub.link_description),
        'tags', pub.link_tags,
        'topics', coalesce((select jsonb_agg(tt.topic_name order by tt.topic_name) from public."LinkTopics" lt join public."Topics" tt on tt.id = lt.topic_id where lt.link_id = l.id), '[]'::jsonb),
        'waiting_time', pub.waiting_time,
        'link_level', pub.link_level,
        'publisher_bonus', pub.publisher_bonus,
        'publisher_bonus_percentage', pub.publisher_bonus_percentage,
        'creation_date', pub.link_creation_date,
        'publication_date', pub.link_publication_date,
        'thumbnail_url', pub.thumbnail_url,
        'impressions', pub.images,
        'clicks', pub.clicks,
        'visits', coalesce(l.number_of_visits, pub.visits)
      ) order by pub.link_publication_date desc nulls last)
      from public."Follows" follow
      join public."Find" pub on pub.owner_id = follow.following_id
      join public."Links" l on trim(l.code) = trim(pub.code)
      left join public."Profiles" lp on lp.id = pub.owner_id
      where follow.follower_id = v_profile.id
        and pub.visibility = 'Public'
        and pub.link_status = 'Active'
        and l.code_status = 'Active'
        and (l.link_expiration_date is null or l.link_expiration_date > now())
    ), '[]'::jsonb),
    'followers', coalesce((
      select jsonb_agg(jsonb_build_object(
        'owner_id', p.id, 'username', p.username, 'avatar_url', p.avatar_url
      ) order by f.followed_at desc)
      from public."Follows" f
      join public."Profiles" p on p.id = f.follower_id
      join public."Members" m on m.owner_id = p.id and m.account_status = 'Active'
      where f.following_id = v_profile.id
    ), '[]'::jsonb),
    'following', coalesce((
      select jsonb_agg(jsonb_build_object(
        'owner_id', p.id, 'username', p.username, 'avatar_url', p.avatar_url
      ) order by f.followed_at desc)
      from public."Follows" f
      join public."Profiles" p on p.id = f.following_id
      join public."Members" m on m.owner_id = p.id and m.account_status = 'Active'
      where f.follower_id = v_profile.id
    ), '[]'::jsonb)
  );
end;
