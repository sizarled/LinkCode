-- LinkCode secure login and session support for Login.html
-- Run this file once in the Supabase SQL Editor after supabase-register-member.sql.

create extension if not exists pgcrypto with schema extensions;

alter table public."Members" enable row level security;

-- One-time compatibility migration: hash any legacy plain-text passwords.
-- New registrations are already stored as bcrypt hashes by register_member.
update public."Members"
set password = crypt(password, gen_salt('bf', 12))
where password not like '$2a$%'
  and password not like '$2b$%'
  and password not like '$2y$%';

-- Private audit table used to rate-limit repeated failed login attempts.
create table if not exists public."MemberLoginAttempts" (
  id bigint generated by default as identity primary key,
  normalized_email text not null,
  requester_ip inet null,
  succeeded boolean not null default false,
  attempted_at timestamp with time zone not null default now()
);

create index if not exists member_login_attempts_lookup_idx
on public."MemberLoginAttempts" (normalized_email, attempted_at desc);

-- Private sessions. Only a SHA-256 hash of each browser token is stored.
create table if not exists public."MemberSessions" (
  session_id uuid primary key default gen_random_uuid(),
  owner_id text not null references public."Members" (owner_id) on delete cascade,
  token_hash text not null unique,
  remember_me boolean not null default false,
  created_at timestamp with time zone not null default now(),
  expires_at timestamp with time zone not null,
  last_seen_at timestamp with time zone not null default now()
);

create index if not exists member_sessions_owner_idx
on public."MemberSessions" (owner_id, expires_at desc);

alter table public."MemberLoginAttempts" enable row level security;
alter table public."MemberSessions" enable row level security;

revoke all on table public."MemberLoginAttempts" from anon, authenticated;
revoke all on table public."MemberSessions" from anon, authenticated;

create or replace function public.login_member(
  p_email text,
  p_password text,
  p_remember_me boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_email text := lower(trim(coalesce(p_email, '')));
  v_member public."Members"%rowtype;
  v_headers jsonb := coalesce(nullif(current_setting('request.headers', true), '')::jsonb, '{}'::jsonb);
  v_forwarded text;
  v_ip inet;
  v_failed_count integer := 0;
  v_token text;
  v_token_hash text;
  v_expires_at timestamp with time zone;
begin
  if char_length(v_email) > 254
     or v_email !~* '^[A-Z0-9._%+\-]+@[A-Z0-9.\-]+\.[A-Z]{2,}$' then
    return jsonb_build_object('success', false, 'reason', 'INVALID_EMAIL');
  end if;

  if p_password is null or char_length(p_password) < 1 or octet_length(p_password) > 72 then
    return jsonb_build_object('success', false, 'reason', 'INVALID_PASSWORD');
  end if;

  v_forwarded := split_part(coalesce(v_headers->>'x-forwarded-for', v_headers->>'x-real-ip', ''), ',', 1);
  begin
    v_ip := nullif(trim(v_forwarded), '')::inet;
  exception when others then
    v_ip := null;
  end;

  -- Serialize attempts for this email and limit brute-force retries.
  perform pg_advisory_xact_lock(hashtext('member-login:' || v_email));

  select count(*)::integer into v_failed_count
  from public."MemberLoginAttempts"
  where normalized_email = v_email
    and succeeded = false
    and attempted_at >= now() - interval '15 minutes'
    and (v_ip is null or requester_ip = v_ip);

  if v_failed_count >= 5 then
    return jsonb_build_object(
      'success', false,
      'reason', 'RATE_LIMITED',
      'retry_after_seconds', 900
    );
  end if;

  select * into v_member
  from public."Members"
  where lower(email) = v_email
  limit 1;

  if not found then
    insert into public."MemberLoginAttempts" (normalized_email, requester_ip, succeeded)
    values (v_email, v_ip, false);
    return jsonb_build_object('success', false, 'reason', 'MEMBER_NOT_FOUND');
  end if;

  if v_member.password <> crypt(p_password, v_member.password) then
    insert into public."MemberLoginAttempts" (normalized_email, requester_ip, succeeded)
    values (v_email, v_ip, false);
    return jsonb_build_object('success', false, 'reason', 'WRONG_PASSWORD');
  end if;

  if v_member.account_status <> 'Active' then
    insert into public."MemberLoginAttempts" (normalized_email, requester_ip, succeeded)
    values (v_email, v_ip, false);
    return jsonb_build_object(
      'success', false,
      'reason', case
        when v_member.account_status = 'Banned' then 'ACCOUNT_BANNED'
        when v_member.account_status = 'Expired' then 'ACCOUNT_EXPIRED'
        else 'ACCOUNT_UNAVAILABLE'
      end
    );
  end if;

  insert into public."MemberLoginAttempts" (normalized_email, requester_ip, succeeded)
  values (v_email, v_ip, true);

  v_token := encode(gen_random_bytes(32), 'hex');
  v_token_hash := encode(digest(v_token, 'sha256'), 'hex');
  v_expires_at := now() + case
    when coalesce(p_remember_me, false) then interval '30 days'
    else interval '12 hours'
  end;

  insert into public."MemberSessions" (
    owner_id,
    token_hash,
    remember_me,
    expires_at
  ) values (
    v_member.owner_id,
    v_token_hash,
    coalesce(p_remember_me, false),
    v_expires_at
  );

  -- Opportunistic cleanup of expired security records.
  delete from public."MemberSessions" where expires_at <= now();
  delete from public."MemberLoginAttempts" where attempted_at < now() - interval '30 days';

  return jsonb_build_object(
    'success', true,
    'owner_id', v_member.owner_id,
    'full_name', v_member.full_name,
    'email', v_member.email,
    'account_status', v_member.account_status,
    'session_token', v_token,
    'session_expires_at', v_expires_at,
    'remember_me', coalesce(p_remember_me, false)
  );
end;
$$;

revoke all on function public.login_member(text, text, boolean) from public;
grant execute on function public.login_member(text, text, boolean) to anon, authenticated;

-- Future Dashboard.html can call this RPC before showing private account data.
create or replace function public.validate_member_session(p_session_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_session public."MemberSessions"%rowtype;
  v_member public."Members"%rowtype;
  v_hash text;
begin
  if p_session_token is null or p_session_token !~ '^[a-f0-9]{64}$' then
    return jsonb_build_object('valid', false, 'reason', 'INVALID_SESSION');
  end if;

  v_hash := encode(digest(p_session_token, 'sha256'), 'hex');

  select * into v_session
  from public."MemberSessions"
  where token_hash = v_hash
  limit 1;

  if not found or v_session.expires_at <= now() then
    if found then delete from public."MemberSessions" where session_id = v_session.session_id; end if;
    return jsonb_build_object('valid', false, 'reason', 'SESSION_EXPIRED');
  end if;

  select * into v_member
  from public."Members"
  where owner_id = v_session.owner_id
  limit 1;

  if not found or v_member.account_status <> 'Active' then
    delete from public."MemberSessions" where session_id = v_session.session_id;
    return jsonb_build_object('valid', false, 'reason', 'ACCOUNT_UNAVAILABLE');
  end if;

  update public."MemberSessions"
  set last_seen_at = now()
  where session_id = v_session.session_id;

  return jsonb_build_object(
    'valid', true,
    'owner_id', v_member.owner_id,
    'full_name', v_member.full_name,
    'email', v_member.email,
    'account_status', v_member.account_status,
    'session_expires_at', v_session.expires_at
  );
end;
$$;

revoke all on function public.validate_member_session(text) from public;
grant execute on function public.validate_member_session(text) to anon, authenticated;

create or replace function public.logout_member(p_session_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if p_session_token is not null and p_session_token ~ '^[a-f0-9]{64}$' then
    delete from public."MemberSessions"
    where token_hash = encode(digest(p_session_token, 'sha256'), 'hex');
  end if;
  return jsonb_build_object('success', true);
end;
$$;

revoke all on function public.logout_member(text) from public;
grant execute on function public.logout_member(text) to anon, authenticated;

-- Members and session tables remain inaccessible through direct anonymous REST queries.
revoke select, insert, update, delete on table public."Members" from anon;
